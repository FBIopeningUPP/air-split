"""Generate the ZMK shield + keymap from layout.py so the key order, matrix and keymap can never drift."""
import os
from layout import build, validate, NROWS

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "zmk-config")
SH = os.path.join(ROOT, "boards", "shields", "air75_split")
for d in (SH, os.path.join(ROOT, "config"), os.path.join(ROOT, "zephyr"), os.path.join(ROOT, ".github", "workflows")):
    os.makedirs(d, exist_ok=True)

keys = build()
errs, info = validate(keys)
assert not errs, errs
NCOL_L = info["L"][1]; NCOL_R = info["R"][1]
assert (NCOL_L, NCOL_R) == (7, 9), (NCOL_L, NCOL_R)

ROW_PINS = [21, 20, 19, 18, 15]                     # SuperMini right header, top to bottom (D21..D15)
COL_PINS_L = [4, 5, 6, 7, 8, 9, 1]                  # left header D4..D9, then D1 (D2/D3 are the OLED's I2C)
COL_PINS_R = [4, 5, 6, 7, 8, 9, 1, 0, "P1.01"]      # ... then D0 and the P1.01 pad near the antenna end
OLED_SDA, OLED_SCL = 2, 3                           # pro_micro_i2c on the nice!nano / SuperMini: D2 = SDA, D3 = SCL

def w(path, text):
    with open(path, "w") as f:
        f.write(text)

# ---- matrix transform + physical layout ----
rc, phys = [], []
for r in range(NROWS):
    for k in [k for k in keys if k["row"] == r]:
        col = k["col_local"] if k["side"] == "L" else NCOL_L + k["col_local"]
        k["col_global"] = col
        rc.append((r, col, k))
def rows_text(items, fmt, per_row=True):
    out, cur = [], -1
    line = []
    for r, c, k in items:
        if r != cur and line:
            out.append(" ".join(line)); line = []
        cur = r
        line.append(fmt(r, c, k))
    out.append(" ".join(line))
    return out

map_lines = rows_text(rc, lambda r, c, k: f"RC({r},{c})")
phys_lines = []
for r, c, k in rc:
    phys_lines.append(f"<&key_physical_attrs {int(round(k['w']*100)):3d} 100 {int(round(k['x0']*100)):4d} {r*100:4d}    0    0    0>")

dtsi = f'''/*
 * Air75-style 65% layout (no function row), split into two halves: 70 keys (the 6.25u space becomes two 2u spaces + Fn).
 * Generated by case/gen_zmk.py from case/layout.py. Edit layout.py, not this file.
 *
 * Matrix: {NROWS} rows x 16 columns. Left half owns columns 0-{NCOL_L-1}, right half columns {NCOL_L}-{NCOL_L+NCOL_R-1}.
 * Diodes: col2row (switch -> diode anode ... cathode/stripe -> ROW wire).
 */
#include <dt-bindings/zmk/matrix_transform.h>
#include <physical_layouts.dtsi>

/ {{
    chosen {{
        zmk,kscan = &kscan0;
        zmk,physical-layout = &air75_split_layout;
        zephyr,display = &oled;
    }};

    kscan0: kscan0 {{
        compatible = "zmk,kscan-gpio-matrix";
        diode-direction = "col2row";
        wakeup-source;

        row-gpios
            = ''' + "\n            , ".join(f"<&pro_micro {p} (GPIO_ACTIVE_HIGH | GPIO_PULL_DOWN)>" for p in ROW_PINS) + f'''
            ;
    }};

    default_transform: keymap_transform0 {{
        compatible = "zmk,matrix-transform";
        columns = <{NCOL_L + NCOL_R}>;
        rows = <{NROWS}>;
        map = <
''' + "\n".join("            " + l for l in map_lines) + f'''
        >;
    }};

    air75_split_layout: air75_split_layout {{
        compatible = "zmk,physical-layout";
        display-name = "Air75 Split";
        kscan = <&kscan0>;
        transform = <&default_transform>;

        keys  //                     w   h    x    y     rot    rx    ry
            = ''' + "\n            , ".join(phys_lines) + '''
            ;
    };
};
'''
dtsi += """
/* 0.91" 128 x 32 SSD1306 OLED on each half, on the SuperMini's I2C pins (D2 = SDA, D3 = SCL). */
&pro_micro_i2c {
    status = "okay";

    oled: ssd1306@3c {
        compatible = "solomon,ssd1306fb";
        reg = <0x3c>;
        width = <128>;
        height = <32>;
        segment-offset = <0>;
        page-offset = <0>;
        display-offset = <0>;
        multiplex-ratio = <31>;
        segment-remap;
        com-invdir;
        com-sequential;
        inversion-on;
        prechargep = <0x22>;
    };
};
"""
w(os.path.join(SH, "air75_split.dtsi"), dtsi)

def cols(pins):
    def one(p):
        if isinstance(p, str):                      # a bare nRF pad, e.g. "P1.01"
            port, pin = p[1:].split(".")
            return f"<&gpio{int(port)} {int(pin)} GPIO_ACTIVE_HIGH>"
        return f"<&pro_micro {p} GPIO_ACTIVE_HIGH>"
    return "\n        , ".join(one(p) for p in pins)

w(os.path.join(SH, "air75_split_left.overlay"), f'''#include "air75_split.dtsi"

/* Left half: {NCOL_L} columns on D2..D8 */
&kscan0 {{
    col-gpios
        = {cols(COL_PINS_L)}
        ;
}};
''')
w(os.path.join(SH, "air75_split_right.overlay"), f'''#include "air75_split.dtsi"

/* Right half: {NCOL_R} columns on D2..D9 and D1 */
&kscan0 {{
    col-gpios
        = {cols(COL_PINS_R)}
        ;
}};

&default_transform {{
    col-offset = <{NCOL_L}>;
}};
''')

w(os.path.join(SH, "Kconfig.shield"), '''config SHIELD_AIR75_SPLIT_LEFT
    def_bool $(shields_list_contains,air75_split_left)

config SHIELD_AIR75_SPLIT_RIGHT
    def_bool $(shields_list_contains,air75_split_right)
''')
w(os.path.join(SH, "Kconfig.defconfig"), '''# The right half is the central (it talks to the computer): it has the bigger 402060 battery.
if SHIELD_AIR75_SPLIT_RIGHT

config ZMK_KEYBOARD_NAME
    default "Air75 Split"

config ZMK_SPLIT_ROLE_CENTRAL
    default y

endif

if SHIELD_AIR75_SPLIT_LEFT || SHIELD_AIR75_SPLIT_RIGHT

config ZMK_SPLIT
    default y

config ZMK_DISPLAY
    default y

if ZMK_DISPLAY

config I2C
    default y

config SSD1306
    default y

endif

endif
''')
w(os.path.join(SH, "air75_split.zmk.yml"), '''file_format: "1"
id: air75_split
name: Air75 Split
type: shield
url: https://zmk.dev/docs/development/hardware-integration/new-shield
requires: [pro_micro]
features:
  - keys
  - display
siblings:
  - air75_split_left
  - air75_split_right
''')

# Radio power: the right half talks to the computer (full +8 dBm). The left half only talks to the right half,
# which is right next to it (or touching it), so 0 dBm is plenty and saves battery.
w(os.path.join(SH, "air75_split_right.conf"), """CONFIG_BT_CTLR_TX_PWR_PLUS_8=y
""")
w(os.path.join(SH, "air75_split_left.conf"), """CONFIG_BT_CTLR_TX_PWR_0=y
""")

# ---- keymap ----
def layer(name, disp, attr):
    lines = []
    for r in range(NROWS):
        row = [k for k in keys if k["row"] == r]
        left = [k[attr] for k in row if k["side"] == "L"]
        right = [k[attr] for k in row if k["side"] == "R"]
        lines.append("                " + "  ".join(f"{b:<14}" for b in left).rstrip() + "      "
                     + "  ".join(f"{b:<14}" for b in right).rstrip())
    return f'''        {name} {{
            display-name = "{disp}";
            bindings = <
''' + "\n".join(lines) + '''
            >;
        };
'''
keymap = '''#include <behaviors.dtsi>
#include <dt-bindings/zmk/keys.h>
#include <dt-bindings/zmk/bt.h>
#include <dt-bindings/zmk/outputs.h>

/*
 * Base: Air75 layout without the function row. Hold Fn (the 1.25u key at the right end of the left half's bottom row):
 *   Fn+Esc `      Fn+1..= F1..F12     Fn+Bksp Delete    Fn+Del Insert     Fn+PgUp Home    Fn+End Print Screen
 *   Fn+Q/W/E/R Bluetooth profile 1-4, Fn+T clear profile, Fn+Y USB output, Fn+U Bluetooth output
 *   Fn+[ / ] brightness, Fn+P play/pause, Fn+M mute, Fn+Up/Down volume, Fn+Left/Right previous/next track
 *   Fn+Backslash bootloader
 */
/ {
    keymap {
        compatible = "zmk,keymap";

''' + layer("base_layer", "Base", "bind") + "\n" + layer("fn_layer", "Fn", "fn") + '''    };
};
'''
keymap = keymap.replace("Hold Fn (left of the right-hand space... the 1.25u key at the end of the left bottom row)",
                        "Hold Fn (the 1.25u key at the right end of the left half's bottom row)")
w(os.path.join(SH, "air75_split.keymap"), keymap)

# ---- repo plumbing ----
w(os.path.join(ROOT, "zephyr", "module.yml"), '''name: zmk-keyboard-air75-split
build:
  settings:
    board_root: .
''')
w(os.path.join(ROOT, "config", "west.yml"), '''manifest:
  remotes:
    - name: zmkfirmware
      url-base: https://github.com/zmkfirmware
  projects:
    - name: zmk
      remote: zmkfirmware
      revision: v0.3
      import: app/west.yml
  self:
    path: config
''')
w(os.path.join(ROOT, "config", "air75_split.conf"), '''# Deep sleep after 15 minutes idle (wakes on any key press)
CONFIG_ZMK_SLEEP=y
CONFIG_ZMK_IDLE_SLEEP_TIMEOUT=900000
# Report both halves' battery level to the computer
CONFIG_ZMK_SPLIT_BLE_CENTRAL_BATTERY_LEVEL_FETCHING=y
CONFIG_ZMK_SPLIT_BLE_CENTRAL_BATTERY_LEVEL_PROXY=y
''')
w(os.path.join(ROOT, "build.yaml"), '''---
include:
  - board: nice_nano_v2
    shield: air75_split_left
  - board: nice_nano_v2
    shield: air75_split_right
  - board: nice_nano_v2
    shield: settings_reset
''')
w(os.path.join(ROOT, ".github", "workflows", "build.yml"), '''name: Build ZMK firmware
on: [push, pull_request, workflow_dispatch]

jobs:
  build:
    uses: zmkfirmware/zmk/.github/workflows/build-user-config.yml@v0.3
''')
print("zmk files written; keys:", len(rc))
