"""Pixel art and key tables for the animated OLED screens, shared by the firmware and the viewer.

gen_zmk.py writes these into zmk-config/src/air75_oled/air75_oled_data.h; build_viewer.py puts the same numbers into the
viewer, so the C renderer (render.c) and its JavaScript twin (viewer/oled_render.js) draw from identical data.
"""
from layout import build

# 3 x 5 pixel font. Each glyph is 5 rows, each row 3 bits (left pixel = 4).
FONT_3X5 = {
    "0": "111 101 101 101 111", "1": "010 110 010 010 111", "2": "111 001 111 100 111", "3": "111 001 011 001 111",
    "4": "101 101 111 001 001", "5": "111 100 111 001 111", "6": "111 100 111 101 111", "7": "111 001 001 010 010",
    "8": "111 101 111 101 111", "9": "111 101 111 001 111",
    "A": "010 101 111 101 101", "B": "110 101 110 101 110", "C": "011 100 100 100 011", "D": "110 101 101 101 110",
    "E": "111 100 110 100 111", "F": "111 100 110 100 100", "G": "011 100 101 101 011", "H": "101 101 111 101 101",
    "I": "111 010 010 010 111", "J": "001 001 001 101 010", "K": "101 101 110 101 101", "L": "100 100 100 100 111",
    "M": "101 111 111 101 101", "N": "110 101 101 101 101", "O": "010 101 101 101 010", "P": "110 101 110 100 100",
    "Q": "010 101 101 110 011", "R": "110 101 110 101 101", "S": "011 100 010 001 110", "T": "111 010 010 010 010",
    "U": "101 101 101 101 111", "V": "101 101 101 101 010", "W": "101 101 111 111 101", "X": "101 101 010 101 101",
    "Y": "101 101 010 010 010", "Z": "111 001 010 100 111",
    "%": "101 001 010 100 101", "-": "000 000 111 000 000", ".": "000 000 000 000 010", ":": "000 010 000 010 000",
    "?": "110 001 010 000 010", "/": "001 001 010 100 100", "<": "001 010 100 010 001", ">": "100 010 001 010 100",
    "+": "000 010 111 010 000", "!": "010 010 010 000 010", "#": "101 111 101 111 101",
}

def font_table():
    """96 glyphs (ASCII 32..127), 5 row bytes each."""
    out = []
    for c in range(32, 128):
        g = FONT_3X5.get(chr(c))
        out.append([int(r, 2) for r in g.split()] if g else [0] * 5)
    return out

def key_tables():
    """Per key position (ZMK keymap order, 0..69): centre and left edge in quarter-units, width in quarter-units,
    row, and the index among the left half's keys (255 for right-half keys)."""
    keys = build()
    qx, x0q, wq, row, left = [], [], [], [], []
    n_left = 0
    for k in keys:
        x0q.append(int(round(k["x0"] * 4)))
        wq.append(int(round(k["w"] * 4)))
        qx.append(int(round(k["cx"] * 4)))
        row.append(k["row"])
        if k["side"] == "L":
            left.append(n_left); n_left += 1
        else:
            left.append(255)
    return dict(qx=qx, x0q=x0q, wq=wq, row=row, left=left, n_left=n_left, n=len(keys))

def c_header():
    f, k = font_table(), key_tables()
    def arr(name, vals, per=16):
        rows = [", ".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
        return f"static const uint8_t {name}[{len(vals)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"
    font = ",\n    ".join("{" + ", ".join(str(b) for b in g) + "}" for g in f)
    return f"""/* Generated by cad/gen_zmk.py from cad/oled_art.py. Edit oled_art.py, not this file. */
#pragma once
#include <stdint.h>

#define AIR_NKEYS {k['n']}
#define AIR_LKEYS {k['n_left']}

/* 3 x 5 font, ASCII 32..127, 5 rows of 3 bits (left pixel = 4) */
static const uint8_t AIR_FONT[96][5] = {{
    {font}
}};

/* per key position, in ZMK keymap order */
{arr("AIR_KEY_QX", k["qx"])}{arr("AIR_KEY_X0Q", k["x0q"])}{arr("AIR_KEY_WQ", k["wq"])}{arr("AIR_KEY_ROW", k["row"])}{arr("AIR_KEY_LEFT", k["left"])}"""

def js_data():
    return dict(font=font_table(), keys=key_tables())

if __name__ == "__main__":
    print(c_header())
